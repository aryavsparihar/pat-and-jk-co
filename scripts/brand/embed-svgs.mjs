#!/usr/bin/env node
/**
 * Embeds the traced brand SVGs (public/brand/*.svg) as inline markup in
 * src/components/brand/svgs.ts, so they can be rendered with currentColor
 * (admin panel logo, the leaf ornament used across the design system).
 *
 * Usage: node scripts/brand/embed-svgs.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const files = {
  logo: 'public/brand/pjk-logo.svg',
  wordmark: 'public/brand/pjk-wordmark.svg',
  sprig: 'public/brand/pjk-sprig.svg',
}

const entries = Object.entries(files).map(([name, file]) => {
  const svg = readFileSync(file, 'utf8')
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1]
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim()
  return `  ${name}: {\n    viewBox: '${viewBox}',\n    markup: ${JSON.stringify(inner)},\n  },`
})

writeFileSync(
  'src/components/brand/svgs.ts',
  `// Generated by scripts/brand/embed-svgs.mjs from public/brand/*.svg — do not edit by hand.\n\nexport const brandSvgs = {\n${entries.join('\n')}\n} as const\n\nexport type BrandSvgName = keyof typeof brandSvgs\n`,
)
console.log('Wrote src/components/brand/svgs.ts')
